def main():
    rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(ROOT, 'work', 'sat_tr_mismatch.tsv'), encoding='utf-8')]
    out = []; miss = []
    for n, (sc, pos, t, kr) in enumerate(rows, 1):
        if n in NEW:
            out.append((sc, pos, NEW[n]))
        elif n in REPL:
            k = kr.replace('　', ' ')          # PC 번역 띄어쓰기는 전각 공백
            for a, b in REPL[n]:
                if a not in k:
                    miss.append((n, a)); break
                k = k.replace(a, b, 1)
            else:
                out.append((sc, pos, k))
    with open(os.path.join(ROOT, 'work', 'tr_fix_mismatch.tsv'), 'w', encoding='utf-8') as w:
        for r in out: w.write('\t'.join(r) + '\n')
    sys.stdout.reconfigure(encoding='utf-8')
    print('수정', len(out), '바꿀 문자열 못 찾음', miss)

if __name__ == '__main__':
    main()
